import type { BillyContractDiff, BillyContractFile } from '../../../shared/billy/contracts.ts'
import type { BillyContext } from '../billy/native.ts'
import { isBillyPath, readBillyText } from '../billy/native.ts'

export const PROTO_ROOT = 'contracts/wire/proto/'

const GO_ROOTS = new Set(['services/backend/api/internal/pb/', 'services/backend/shared/pb/'])
const TS_ROOT = 'clients/web/packages/proto-gen/src/proto/'
const PY_ROOT = 'services/ai/core/foundation/models/proto/'
const SWIFT_ROOT = 'clients/apple/Shared/Sources/BillyVoxProto/'
const HEADER_BYTES = 8192
const MAX_HEADERS = 32
const PROTO_PATH = /^(?:[\w-]+\/)*[\w-]+\.proto$/u
const SOURCE_HEADER = /^\s*(?:\/\/|#)\s*(?:source:\s*|@generated from file\s+)([^\s()]+\.proto)(?:\s|$)/imu
const GENERATOR_HEADER = /^\s*(?:\/\/|#)\s*(?:@generated by |(?:code )?generated by )/imu

interface Binding {
  path: string
  stem: string
  flattened: boolean
}

function binding(path: string, declaredRoots: readonly string[]): Binding | null {
  const root = declaredRoots.find(prefix => prefix.endsWith('/') && path.startsWith(prefix))
  if (!root) return null
  let relative = path.slice(root.length)
  if (root === SWIFT_ROOT) {
    const [, stem] = /^([\w-]+)\.(?:pb|connect)\.swift$/u.exec(relative) ?? []
    return stem ? { path, stem, flattened: true } : null
  }

  let suffix: RegExp
  if (GO_ROOTS.has(root)) {
    if (relative.endsWith('.connect.go')) relative = relative.replace(/\/[\w]+connect\//u, '/')
    suffix = /(?:_vtproto|_grpc)?\.pb\.go$|\.connect\.go$/u
  } else if (root === TS_ROOT) {
    suffix = /(?:_pb|-[\w]+_connectquery)\.ts$/u
  } else if (root === PY_ROOT) {
    suffix = /_pb2(?:_grpc)?\.pyi?$|\.documentation\.json$/u
  } else {
    return null
  }
  const stem = relative.replace(suffix, '')
  return stem !== relative && PROTO_PATH.test(`${stem}.proto`) ? { path, stem, flattened: false } : null
}

function protoName(path: string): string | null {
  const relative = path.startsWith(PROTO_ROOT) ? path.slice(PROTO_ROOT.length) : ''
  return PROTO_PATH.test(relative) ? relative : null
}

function matches(output: Binding, proto: string) {
  const stem = proto.slice(0, -'.proto'.length)
  return output.stem === (output.flattened ? stem.replaceAll('/', '_') : stem)
}

async function header(context: BillyContext, output: Binding): Promise<string | null> {
  try {
    const text = await readBillyText(context.root, output.path, HEADER_BYTES, context.signal, true)
    if (!GENERATOR_HEADER.test(text)) return null
    const [, source] = SOURCE_HEADER.exec(text) ?? []
    return source && PROTO_PATH.test(source) && matches(output, source) ? source : null
  } catch {
    context.signal.throwIfAborted()
    return null
  }
}

async function available(context: BillyContext, path: string, changed: ReadonlySet<string>) {
  if (changed.has(path)) return true
  try {
    await readBillyText(context.root, path, 1, context.signal, true)
    return true
  } catch {
    context.signal.throwIfAborted()
    return false
  }
}

export async function protobufGroups(
  context: BillyContext,
  roots: readonly string[],
  selected: string,
  changed: ReadonlySet<string>,
): Promise<BillyContractDiff> {
  const source = protoName(selected)
  const selectedBinding = binding(selected, roots)
  if (!source && !selectedBinding) return { groups: [], limited: false }

  const headers = new Map<string, Promise<string | null>>()
  function sourceHeader(output: Binding) {
    const pending = headers.get(output.path)
    if (pending) return pending
    if (headers.size >= MAX_HEADERS) return Promise.resolve(null)
    const observed = header(context, output)
    headers.set(output.path, observed)
    return observed
  }

  const declaredSource = selectedBinding ? await sourceHeader(selectedBinding) : null
  let candidates = source ? [source] : declaredSource ? [declaredSource] : []
  if (!candidates.length && selectedBinding) {
    if (selectedBinding.flattened) {
      candidates = [...changed].flatMap(path => {
        const proto = protoName(path)
        return proto && matches(selectedBinding, proto) ? [proto] : []
      })
    } else {
      candidates = [`${selectedBinding.stem}.proto`]
    }
  }
  const valid = await Promise.all(
    candidates.slice(0, MAX_HEADERS).map(async proto => {
      const path = `${PROTO_ROOT}${proto}`
      return isBillyPath(path) && (await available(context, path, changed)) ? proto : null
    }),
  )
  const outputs = new Map<string, Binding>()
  for (const path of changed) {
    const output = binding(path, roots)
    if (output) outputs.set(path, output)
  }
  if (selectedBinding) outputs.set(selectedBinding.path, selectedBinding)

  let limited = candidates.length > MAX_HEADERS
  const groups = await Promise.all(
    valid
      .filter(proto => proto !== null)
      .map(async proto => {
        const path = `${PROTO_ROOT}${proto}`
        const related = [...outputs.values()].filter(output => matches(output, proto))
        if (related.length > MAX_HEADERS) limited = true
        const projected = await Promise.all(
          related.slice(0, MAX_HEADERS).map(async (output): Promise<BillyContractFile | null> => {
            const observed = await sourceHeader(output)
            if (observed && observed !== proto) return null
            return {
              path: output.path,
              changed: changed.has(output.path),
              confidence: observed ? 'header' : 'candidate',
              shared: false,
            }
          }),
        )
        return {
          id: 'proto',
          sourceKind: 'protobuf' as const,
          sources: [{ path, changed: changed.has(path), confidence: 'declared' as const, shared: false }],
          outputs: projected.filter(output => output !== null),
        }
      }),
  )
  return { groups, limited }
}
