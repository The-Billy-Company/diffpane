import assert from 'node:assert/strict'
import { mkdir, mkdtemp, realpath, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { test } from 'vite-plus/test'
import { readBillyContractDiff } from '../../../electron/tools/billy-contracts/contracts.ts'
import { createBillyContext } from '../../../electron/tools/billy/native.ts'
import { isBillyContractDiff } from '../../../shared/billy/contracts.ts'

const TAXONOMY = 'contracts/domain/tools/taxonomy.toml'
const COLLECTIVE = 'contracts/domain/collective/collective.toml'
const CHAT = 'contracts/wire/proto/grpc/chatpb/chat.proto'
const RELAY = 'contracts/wire/proto/shared/relaypb/v1/relay.proto'
const GO_LEAF = 'services/backend/api/internal/pb/shared/relaypb/v1/relay.pb.go'
const TS_LEAF = 'clients/web/packages/proto-gen/src/proto/shared/relaypb/v1/relay_pb.ts'
const SWIFT_LEAF = 'clients/apple/Shared/Sources/BillyVoxProto/shared_relaypb_v1_relay.pb.swift'

async function fixture(onFinish: (callback: () => Promise<void>) => void) {
  const root = await realpath(await mkdtemp(path.join(tmpdir(), 'diffpane-contracts-')))
  onFinish(() => rm(root, { recursive: true, force: true }))
  async function write(relative: string, text: string) {
    const file = path.join(root, relative)
    await mkdir(path.dirname(file), { recursive: true })
    await writeFile(file, text)
  }
  await write(
    'contracts/operate/codegen/generators.toml',
    `
[[generator]]
id = "gen-areas"
source = "${TAXONOMY}"
outputs = ["${CHAT}", "areas_gen.py"]

[[generator]]
id = "gen-collective"
source = [ "${COLLECTIVE}" ]
outputs = ["${CHAT}"]

[[generator]]
id = "proto"
source = [ "contracts/wire/proto/" ]
outputs = ["services/backend/api/internal/pb/", "clients/web/packages/proto-gen/src/proto/", "clients/apple/Shared/Sources/BillyVoxProto/"]

[[generator]]
id = "gen-stat"
source = "."
outputs = []
`,
  )
  const context = createBillyContext(root, new AbortController().signal)
  return { context, write }
}

test('taxonomy links only changed projections and reports the generator’s section in a shared output', async t => {
  const { context, write } = await fixture(t.onTestFinished)
  await write(
    CHAT,
    [
      'syntax = "proto3";',
      '// gen-areas:categories-start (sourced from taxonomy)',
      'enum ToolCategory {}',
      '// gen-areas:categories-end',
      '// gen-collective:agents-start',
      'enum AgentRole {}',
      '// gen-collective:agents-end',
      'message Authored {}',
    ].join('\n'),
  )

  const result = await readBillyContractDiff(context, { path: TAXONOMY, changedPaths: [TAXONOMY, CHAT, 'other.py'] })
  assert.ok(isBillyContractDiff(result))
  assert.deepEqual(result.groups, [
    {
      id: 'gen-areas',
      sourceKind: 'generator',
      sources: [{ path: TAXONOMY, changed: true, confidence: 'declared', shared: false }],
      outputs: [
        {
          path: CHAT,
          changed: true,
          confidence: 'declared',
          shared: true,
          sections: [{ name: 'categories', start: 2, end: 4 }],
        },
      ],
    },
  ])

  const reverse = await readBillyContractDiff(context, { path: CHAT, changedPaths: [CHAT] })
  assert.deepEqual(
    reverse.groups.map(group => group.id),
    ['proto', 'gen-areas', 'gen-collective'],
  )
  assert.deepEqual(
    reverse.groups.flatMap(group => group.sources.map(file => [file.path, file.changed])),
    [
      [CHAT, true],
      [TAXONOMY, false],
      [COLLECTIVE, false],
    ],
  )
  assert.deepEqual(reverse.groups.at(-1)?.outputs[0]?.sections, [{ name: 'agents', start: 5, end: 7 }])
})

test('Relay bindings point back to their schema with header or naming confidence', async t => {
  const { context, write } = await fixture(t.onTestFinished)
  await Promise.all([
    write(RELAY, 'syntax = "proto3";'),
    write(GO_LEAF, '// Code generated by protoc-gen-go.\n// source: shared/relaypb/v1/relay.proto\n'),
    write(
      SWIFT_LEAF,
      '// Generated by the Swift generator plugin for the protocol buffer compiler.\n// Source: shared/relaypb/v1/relay.proto\n',
    ),
  ])
  const missing = 'clients/web/packages/proto-gen/src/proto/connect/auth/relaytransportpb/v1/relaytransport_pb.ts'
  const changedPaths = [GO_LEAF, TS_LEAF, SWIFT_LEAF, missing]
  const result = await readBillyContractDiff(context, { path: SWIFT_LEAF, changedPaths })
  assert.equal(result.groups.length, 1)
  assert.deepEqual(result.groups[0]?.sources, [{ path: RELAY, changed: false, confidence: 'declared', shared: false }])
  assert.deepEqual(
    result.groups[0]?.outputs.map(data => [data.path, data.confidence]),
    [
      [GO_LEAF, 'header'],
      [TS_LEAF, 'candidate'],
      [SWIFT_LEAF, 'header'],
    ],
  )
})

test('a Swift header resolves flattening collisions instead of attributing both schemata', async t => {
  const { context, write } = await fixture(t.onTestFinished)
  const source = 'contracts/wire/proto/shared/a_b/name.proto'
  const other = 'contracts/wire/proto/shared/a/b_name.proto'
  const swift = 'clients/apple/Shared/Sources/BillyVoxProto/shared_a_b_name.pb.swift'
  await Promise.all([
    write(source, 'syntax = "proto3";'),
    write(other, 'syntax = "proto3";'),
    write(swift, '// Generated by the Swift generator.\n// Source: shared/a/b_name.proto\n'),
  ])
  const changedPaths = [source, other, swift]
  assert.deepEqual((await readBillyContractDiff(context, { path: source, changedPaths })).groups[0]?.outputs, [])
  assert.equal((await readBillyContractDiff(context, { path: swift, changedPaths })).groups[0]?.sources[0]?.path, other)
  await assert.rejects(readBillyContractDiff(context, { path: '../unsafe', changedPaths: [] }), /Choose a file/u)
})
